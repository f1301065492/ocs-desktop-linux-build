		'检测到当前课程为闯关模式（有小旗帜图标）, 但是已经重复进入多次，请手动完成章节测试，然后手动点击下一章。',
		'📢 请手动进入作业/考试，如果未开始答题，请尝试刷新页面。',
		'播放音视频失败，您必须先点击一次页面上的任意位置脚本才能进行音视频的播放。',
		// 设置类提醒（不推送）
		'题库配置不能为空，请重新配置。',
		'请先在 通用-全局设置 配置题库，才能进行在线搜题。',
